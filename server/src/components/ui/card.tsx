import { cn } from "@/lib/utils";

function Card({
  className,
  size = "default",
  ...props
}: React.ComponentProps<"div"> & { size?: "default" | "sm" }) {
  return (
    <div
      data-slot="card"
      data-size={size}
      className={cn(
        "panel group/card flex flex-col gap-4 rounded-lg border border-[var(--border)] bg-card p-5 text-card-foreground shadow-none data-[size=sm]:gap-3 data-[size=sm]:p-4",
        className,
      )}
      {...props}
    />
  );
}

